# Phase 16: GDM (login screen) — 125% interface scaling + monitor layout.

_f0=$FAIL_COUNT
GDM_DBNAME="gdm"
GDM_DBDIR="/etc/dconf/db/${GDM_DBNAME}.d"
GDM_PROFILE="/etc/dconf/profile/${GDM_DBNAME}"
GDM_SCALE_KEYFILE="${GDM_DBNAME}d/99-gdm-scale"
GDM_SCALING="1.25"

# --- GDM dconf profile ------------------------------------------------------
# The greeter runs with DCONF_PROFILE=gdm. Without this profile it does not read
# the system-db:gdm database and the user list disappears (known GDM 50 bug).
if [ ! -f "$GDM_PROFILE" ]; then
  install -d -m 755 /etc/dconf/profile
  cat > "$GDM_PROFILE" <<EOF
user-db:user
system-db:${GDM_DBNAME}
file-db:/usr/share/gdm/greeter-dconf-defaults
EOF
  ok "GDM: dconf profile created ($GDM_PROFILE)"
else
  ok "GDM: dconf profile already exists"
fi

# --- greeter interface scaling ---------------------------------------------
# The 'scaling-factor' of the org.gnome.desktop.interface schema is uint32 (only
# 1/2/3/4), so 125% is only possible via text-scaling-factor (double 0.5-3.0).
#
# The keyfile is numbered 99- on purpose: within the same .d directory dconf
# applies the keyfiles in lexicographic order and the LAST one wins. This way
# this file overrides 95-gdm-settings (generated by the GdmSettings extension)
# regardless of installation order.
install -d -m 755 "$GDM_DBDIR"
cat > "$GDM_DBDIR/99-gdm-scale" <<EOF
# GDM interface scaling (login screen).
# Generated by fedorapi — overrides the GdmSettings extension's 95-gdm-settings.
[org/gnome/desktop/interface]
text-scaling-factor=${GDM_SCALING}
EOF
chmod 644 "$GDM_DBDIR/99-gdm-scale"
try_warn dconf update
ok "GDM: text-scaling-factor=${GDM_SCALING} applied"

# --- greeter monitor layout ------------------------------------------------
# GDM 49+ (Fedora 45) no longer uses the static gdm user: it spins up a
# dynamic greeter user whose XDG_CONFIG_HOME is /var/lib/gdm/seat0/config.
# The legacy /var/lib/gdm/.config path is kept for older GDM releases.
# Without copying monitors.xml there, the login screen ends up at a different
# scale/layout than the session.
GDM_HOME="/var/lib/gdm"
if [ -f "$SUH/.config/monitors.xml" ]; then
  # legacy path
  install -d -m 755 "$GDM_HOME/.config"
  install -m 644 "$SUH/.config/monitors.xml" "$GDM_HOME/.config/monitors.xml"
  chown gdm:gdm "$GDM_HOME/.config/monitors.xml" 2>/dev/null || chown root:root "$GDM_HOME/.config/monitors.xml"
  # F45+ dynamic-user path
  install -d -m 700 "$GDM_HOME/seat0/config"
  install -m 644 "$SUH/.config/monitors.xml" "$GDM_HOME/seat0/config/monitors.xml"
  chown root:root "$GDM_HOME/seat0/config/monitors.xml"
  # global fallback (read by mutter regardless of the user)
  install -m 644 "$SUH/.config/monitors.xml" /etc/xdg/monitors.xml
  ok "GDM: monitors.xml copied (seat0/config + legacy + /etc/xdg)"
else
  warn "GDM: \$SUH/.config/monitors.xml missing — greeter stays at the default scale"
fi

# --- sync the GDM text scale with the extension ---------------------------
# The GdmSettings extension (flatpak) rewrites 95-gdm-settings from its dconf
# (io.github.realmazharhussain.GdmSettings/fonts/scaling-factor). Keeping the
# value aligned stops the extension's "apply" from undoing 99-gdm-scale. The
# schema lives inside the flatpak, so the user dconf is read directly instead of
# gsettings.
GSCHEMA="io.github.realmazharhussain/GdmSettings"
_dconf_dump=$(as_user dconf dump / 2>/dev/null || true)
if printf '%s' "$_dconf_dump" | grep -q "GdmSettings/fonts"; then
  _cur=$(printf '%s' "$_dconf_dump" | grep -A6 "GdmSettings/fonts" | grep -oE "scaling-factor=[0-9.]+" | cut -d= -f2)
  if [ "$_cur" = "$GDM_SCALING" ]; then
    ok "GDM: GdmSettings extension already has scaling-factor=$GDM_SCALING"
  else
    # The extension reads this value; adjust the user dconf.
    if as_user dconf write "/$GSCHEMA/fonts/scaling-factor" "$GDM_SCALING" 2>/dev/null; then
      ok "GDM: GdmSettings extension synced ($GDM_SCALING)"
    else
      warn "GDM: could not sync the GdmSettings extension (scaling-factor=$_cur)"
    fi
  fi
else
  warn "GDM: GdmSettings extension not configured — skipping sync"
fi

phase_end "$_f0" "GDM configured (interface ${GDM_SCALING})"
